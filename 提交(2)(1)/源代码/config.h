/**
 * @file config.h
 * @brief 双轮差速移动机器人配置文件
 *
 * 定义机器人物理参数、控制参数和系统常量
 * 
 * 日期：2025-11-17
 */

#ifndef CONFIG_H
#define CONFIG_H

// ============================================================================
// 机器人物理参数 (Robot Physical Parameters)
// ============================================================================

/**
 * 后驱轮距 (cm)
 * 两主动轮中心之间的距离，几何中心O位于两轮连线中点
 */
#define WHEEL_BASE_W 30.0f

/**
 * 机器人长度 (cm)
 * 车身前后方向的尺寸
 */
#define ROBOT_LENGTH 40.0f

/**
 * 机器人宽度 (cm)
 * 车身左右方向的尺寸（通常等于轮距）
 */
#define ROBOT_WIDTH 30.0f

// ============================================================================
// 控制参数 (Control Parameters)
// ============================================================================

/**
 * 基准转速 V₀ (cm/s)
 * 主动轮理想线速度，用于原地旋转
 * 理想状态：V_L = -V₀, V_R = +V₀
 */
#define BASE_SPEED_V0 5.0f

/**
 * 补偿系数 k (cm/(s·cm))
 * 偏移量到补偿速度的转换系数
 * 补偿速度：ΔV = k × Δd
 *
 * 推荐值：k ∈ [0.3, 0.8]
 * - k过大：补偿过度，可能振荡
 * - k过小：补偿缓慢，收敛时间长
 */
#define COMPENSATION_COEFF_K 0.5f

/**
 * 偏移阈值 (cm)
 * 当 |Δd| < 阈值时，认为旋转中心已对准，不需要补偿
 * 防止频繁小幅度调整导致抖动
 */
#define OFFSET_THRESHOLD 0.1f

/**
 * 最大偏移量 (cm)
 * 允许的最大偏移量，超过此值需要重新初始化
 * 设置为轮距的50%
 */
#define MAX_OFFSET (WHEEL_BASE_W * 0.5f)

// ============================================================================
// 验证标准 (Validation Criteria)
// ============================================================================

/**
 * 成功标准：偏移量精度 (cm)
 * 稳定状态下，偏移量应满足：|Δd| ≤ 5% × W = 1.5 cm
 */
#define SUCCESS_OFFSET_TOLERANCE (WHEEL_BASE_W * 0.05f)  // 1.5 cm

/**
 * 成功标准：速度精度 (cm/s)
 * 补偿后，左右轮速度之和应满足：|V_L + V_R| ≤ 0.5 cm/s
 */
#define SUCCESS_SPEED_TOLERANCE 0.5f

/**
 * 成功标准：收敛时间 (秒)
 * 从初始偏移到稳定状态的时间应 ≤ 3 秒
 */
#define SUCCESS_CONVERGE_TIME 3.0f

// ============================================================================
// 数学常量 (Mathematical Constants)
// ============================================================================

/**
 * 圆周率 π
 */
#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

/**
 * 弧度转角度系数
 * degrees = radians × RAD_TO_DEG
 */
#define RAD_TO_DEG (180.0f / M_PI)

/**
 * 角度转弧度系数
 * radians = degrees × DEG_TO_RAD
 */
#define DEG_TO_RAD (M_PI / 180.0f)

// ============================================================================
// 仿真参数 (Simulation Parameters)
// ============================================================================

/**
 * 仿真时间步长 (秒)
 * 控制循环的时间间隔
 */
#define TIME_STEP 0.05f  // 50ms，对应20Hz控制频率

/**
 * 仿真总时长 (秒)
 * 用于测试的仿真运行时间
 */
#define SIMULATION_DURATION 10.0f

/**
 * 数据记录间隔 (次)
 * 每隔多少次控制循环记录一次数据
 */
#define DATA_LOG_INTERVAL 5  // 每250ms记录一次

// ============================================================================
// 调试开关 (Debug Flags)
// ============================================================================

/**
 * 启用详细日志
 * 1：打印详细的调试信息（控制台程序用）
 * 0：关闭调试输出（图形界面程序用）
 */
#define ENABLE_VERBOSE_LOG 0

/**
 * 启用数据导出
 * 1：将仿真数据导出到CSV文件
 * 0：不导出数据
 */
#define ENABLE_DATA_EXPORT 0

#endif // CONFIG_H
